import assert from 'node:assert/strict';
import { createServer } from 'vite';

const server = await createServer({ appType: 'custom', server: { middlewareMode: true }, optimizeDeps: { noDiscovery: true, include: [] } });
try {
    const module = await server.ssrLoadModule('/src/analytics/collector.ts');
    assert.equal(typeof module.AnalyticsTracker, 'function', 'Analytics tracker must exist');
    const { AnalyticsTracker } = module;
    const { terminalOutcome } = await server.ssrLoadModule('/src/analytics/gameTracking.ts');
    const classic = { edition: { id: 'classic', championOpponents: [] }, wins: 12, lives: 1, currentOpponentId: 'champion', defeatedOpponentIds: [] };
    assert.equal(terminalOutcome(classic, 'WIN'), 'victory');
    assert.equal(terminalOutcome(classic, 'LOSS'), 'defeat');
    assert.equal(terminalOutcome(classic, 'DRAW'), undefined);
    assert.equal(terminalOutcome({ ...classic, wins: 11, lives: 2 }, 'WIN'), undefined);
    const infinite = { ...classic, edition: { id: 'infinite', championOpponents: [{ id: 'a' }, { id: 'b' }] }, defeatedOpponentIds: ['a'], currentOpponentId: 'b' };
    assert.equal(terminalOutcome(infinite, 'WIN'), 'victory');
    assert.equal(terminalOutcome({ ...infinite, currentOpponentId: 'a' }, 'WIN'), undefined);
    const storage = () => {
        const data = new Map();
        return { getItem: key => data.get(key) ?? null, setItem: (key, value) => data.set(key, value), removeItem: key => data.delete(key) };
    };
    let sequence = 0;
    let now = new Date('2026-11-02T15:59:00Z');
    const persistent = storage(), session = storage();
    const received = [];
    let offline = true;
    const options = { storage: persistent, sessionStorage: session, enabled: true, version: 'test-release', clock: () => now, id: () => `00000000-0000-4000-8000-${String(++sequence).padStart(12, '0')}`, send: async events => { if (offline) throw new Error('offline'); received.push(...events); return events.map(event => event.eventId); } };
    const tracker = new AnalyticsTracker(options);
    tracker.startVisit(); tracker.startVisit();
    const input = { edition: 'classic', difficulty: 'NORMAL', turn: 1, wins: 0, lives: 6, opponentId: 'brock', opponentDifficulty: 'EASY', playerTeam: [null, { templateId: 'rattata', name: '小拉達', level: 1, stats: { attack: 2, hp: 3, maxHp: 3 }, synergies: ['Normal'] }, null, null, null], enemyTeam: [], synergies: { Normal: 2 }, psychicN: 2 };
    tracker.startBattle(input, true);
    tracker.finishBattle('WIN');
    tracker.startBattle(input);
    tracker.startBattle(input);
    input.playerTeam[1].stats.attack = 99;
    tracker.finishBattle('WIN'); tracker.finishBattle('WIN');
    await tracker.flush();
    assert.equal(received.length, 0, 'Offline delivery is retained');
    offline = false;
    const reloaded = new AnalyticsTracker(options);
    reloaded.startVisit();
    await reloaded.flush();
    assert.equal(received.filter(event => event.kind === 'visit').length, 1, 'Refresh/retry must not inflate visits');
    assert.equal(received.filter(event => event.kind === 'battle_start').length, 1, 'Tutorial and duplicate callbacks excluded');
    assert.equal(received.filter(event => event.kind === 'battle_end').length, 1);
    const start = received.find(event => event.kind === 'battle_start');
    assert.equal(start.payload.playerTeam.length, 5);
    assert.equal(start.payload.playerTeam[0], null);
    assert.equal(start.payload.playerTeam[1].attack, 2, 'Snapshots must not change after combat mutations');
    const end = received.find(event => event.kind === 'battle_end');
    assert.equal(end.runId, start.runId);
    assert.equal(end.battleId, start.battleId);
    await reloaded.flush();
    assert.equal(received.length, 3, 'Acknowledged events must leave queue');
    now = new Date('2026-11-02T16:30:01Z');
    reloaded.startVisit();
    await reloaded.flush();
    assert.equal(received.filter(event => event.kind === 'visit').length, 2);
    const disabled = new AnalyticsTracker({ ...options, enabled: false });
    disabled.startVisit(); disabled.startBattle(input); disabled.finishBattle('WIN', 'victory');
    await disabled.flush();
    assert.equal(received.length, 4, 'Disabled analytics must not emit');
    tracker.finishRun('abandoned');
    await tracker.flush();
    assert.equal(received.at(-1).payload.outcome, 'abandoned');
    const noStorage = { getItem() { throw new Error('blocked'); }, setItem() { throw new Error('blocked'); }, removeItem() {} };
    const privateMode = new AnalyticsTracker({ ...options, storage: noStorage, sessionStorage: noStorage });
    privateMode.startVisit(); await privateMode.flush();
    assert.equal(received.at(-1).kind, 'visit', 'Storage failure must not break game or delivery');
    const staleStorage = storage(), staleSession = storage();
    const staleReceived = [];
    const staleOptions = { ...options, storage: staleStorage, sessionStorage: staleSession, send: async events => {
        if (events.some(event => now.getTime() - Date.parse(event.clientAt) >= 7 * 86400000)) throw new Error('400 expired batch');
        staleReceived.push(...events); return events.map(event => event.eventId);
    } };
    const oldTracker = new AnalyticsTracker(staleOptions);
    oldTracker.startVisit();
    now = new Date(now.getTime() + 8 * 86400000);
    const returning = new AnalyticsTracker(staleOptions);
    returning.startVisit(); await returning.flush();
    assert.equal(staleReceived.length, 1, 'Expired offline events must not block fresh visits');
    assert.equal(staleReceived[0].clientAt, now.toISOString());
    console.log('Analytics tracker: deduplication, offline retry, immutable five-slot snapshots, tutorial exclusion and disabled-storage checks passed.');
} finally {
    await server.close();
}
